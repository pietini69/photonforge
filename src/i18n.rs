//! Bilingual UI localization (English & Finnish) for PhotonForge.
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UiLang {
    English = 0,
    Finnish = 1,
}

static CURRENT_LANG: AtomicU8 = AtomicU8::new(0); // Default to English for global release

pub fn init_from_env() {
    for var in &["LANG", "LC_ALL", "LC_MESSAGES"] {
        if let Ok(lang) = std::env::var(var) {
            if lang.to_lowercase().starts_with("fi") {
                CURRENT_LANG.store(UiLang::Finnish as u8, Ordering::Relaxed);
                return;
            }
        }
    }

    #[cfg(target_os = "macos")]
    {
        if let Ok(output) = std::process::Command::new("defaults")
            .args(["read", "-g", "AppleLocale"])
            .output()
        {
            if let Ok(s) = std::str::from_utf8(&output.stdout) {
                if s.trim().to_lowercase().starts_with("fi") {
                    CURRENT_LANG.store(UiLang::Finnish as u8, Ordering::Relaxed);
                    return;
                }
            }
        }
    }
}

pub fn current_lang() -> UiLang {
    match CURRENT_LANG.load(Ordering::Relaxed) {
        1 => UiLang::Finnish,
        _ => UiLang::English,
    }
}

pub fn set_lang(lang: UiLang) {
    CURRENT_LANG.store(lang as u8, Ordering::Relaxed);
}

pub fn toggle_lang() -> UiLang {
    let next = match current_lang() {
        UiLang::English => UiLang::Finnish,
        UiLang::Finnish => UiLang::English,
    };
    set_lang(next);
    next
}

